import React, { useEffect, useState } from 'react'
import { api } from '../api.js'
import { Spinner } from '../components/shared.jsx'

export default function DataProfile() {
  const [reports, setReports] = useState(null)
  const [selected, setSelected] = useState('')
  const [err, setErr] = useState(null)

  useEffect(() => {
    api.dataProfiles()
      .then((d) => {
        setReports(d.items)
        setSelected((prev) => prev || d.items[0]?.name || '')
      })
      .catch((e) => setErr(e.message))
  }, [])

  if (err) return <div className="py-16 text-center text-flag text-sm">Couldn't load data profiles: {err}</div>
  if (!reports) return <Spinner label="Loading data profiles…" />

  const current = reports.find((r) => r.name === selected)

  return (
    <div className="space-y-4">
      <div className="card p-6">
        <div className="label">Data Quality</div>
        <h1 className="text-2xl font-semibold mt-1">Data Profile</h1>
        <p className="text-sm text-inkmute mt-3 max-w-3xl leading-relaxed">
          Per-column distributions, missingness, and summary statistics generated by{' '}
          <a href="https://github.com/ydataai/ydata-profiling" target="_blank" rel="noopener noreferrer"
            className="text-teal hover:underline">ydata-profiling</a>. Reports are static snapshots:
          they reflect the data as of when they were generated, not the live source.
        </p>
        {reports.length > 0 && (
          <div className="flex flex-wrap items-center gap-3 mt-4 text-sm">
            <select value={selected} onChange={(e) => setSelected(e.target.value)}
              aria-label="Choose a data profile" className="border border-line rounded-sm px-2 py-1 bg-white">
              {reports.map((r) => <option key={r.name} value={r.name}>{r.name}</option>)}
            </select>
            {current && (
              <>
                <span className="text-inkmute">
                  generated {new Date(current.generated_at).toLocaleString()} · {current.size_kb.toLocaleString()} KB
                </span>
                <a href={api.dataProfileUrl(current.name)} target="_blank" rel="noopener noreferrer"
                  className="text-teal hover:underline">Open in a new tab ↗</a>
              </>
            )}
          </div>
        )}
      </div>

      {reports.length === 0 ? (
        <div className="card p-6 text-sm text-inkmute leading-relaxed">
          No profiles yet. Generate one from the repo root, then reload this page:
          <pre className="mt-3 bg-paper border border-line rounded-sm p-3 overflow-x-auto text-xs text-ink">{`python scripts/generate_profile.py                                  # scraped listings
python scripts/generate_profile.py path/to/train.parquet --name training_set`}</pre>
        </div>
      ) : (
        <div className="card p-2">
          <iframe key={selected} src={api.dataProfileUrl(selected)} title={`Data profile: ${selected}`}
            className="w-full border border-line rounded-sm" style={{ height: '80vh' }} />
        </div>
      )}
    </div>
  )
}
